#!/usr/bin/env python3
"""Check that no board plays or zooms a file that is gone.

    python3 _tool/mark_lost.py            # every product
    python3 _tool/mark_lost.py MERRY      # one product

Every board is generated by x_systems/video_boards/tools/build_board.py, which
draws a lost take (a missing file whose name is in content/lost_takes.txt)
greyed out, and refuses to build when a missing file is not listed. So this
tool never edits a board any more - it only reports a board that points at a
file that is not on disk:

    <button class="vfac" data-src="<gone>.mp4">    a play button that would open a broken player
    data-full="<gone>.png"                         a zoom target that would open nothing

  * listed in lost_takes.txt  -> the board is stale: rebuild it (build_board.py PRODUCT)
  * not listed                -> restore the file, or record it in lost_takes.txt with Daniel

Exit 0 = every reference resolves. Exit 1 = something to fix. Exit 2 = the
product filter matched nothing.
"""
import os, re, sys, html

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def lost_names(base):
    p = os.path.join(base, 'content', 'lost_takes.txt')
    if not os.path.exists(p):
        return set()
    return {l.strip() for l in open(p, encoding='utf-8')
            if l.strip() and not l.startswith('#')}


def run(product):
    base = os.path.join(ROOT, product)
    p = os.path.join(base, 'video_board.html')
    if not os.path.exists(p):
        print(f'{product}: no video_board.html')
        return 1
    doc = open(p, encoding='utf-8').read()
    lost = lost_names(base)
    on_disk = set()                       # one walk instead of one stat per reference
    for d, dirs, files in os.walk(base):
        r = os.path.relpath(d, base).replace(os.sep, '/')
        for f in files:
            on_disk.add(f if r == '.' else r + '/' + f)

    stale, unlisted = set(), set()
    for url in re.findall(r'(?:data-src|data-full)="([^"]+)"', doc):
        u = html.unescape(url)
        if u.startswith(('http:', 'https:', 'data:', '#', 'mailto:')) or u.replace('\\', '/') in on_disk:
            continue
        name = os.path.basename(u)
        base_name = re.sub(r'_g\d+(_g\d+)(\.\w+)$', r'\1\2', name)
        (stale if (name in lost or base_name in lost) else unlisted).add(u)

    if stale:
        print(f'{product}: {len(stale)} lost take(s) still live on the board - rebuild it '
              '(python3 x_systems/video_boards/tools/build_board.py "' + product + '"):')
        for u in sorted(stale):
            print('  ' + u)
    if unlisted:
        print(f'{product}: {len(unlisted)} dead reference(s) NOT in content/lost_takes.txt - restore the file '
              'or record it with Daniel:')
        for u in sorted(unlisted):
            print('  ' + u)
    if not stale and not unlisted:
        print(f'{product}: every board reference resolves')
    return 1 if (stale or unlisted) else 0


def main():
    args = [a for a in sys.argv[1:] if not a.startswith('-')]
    products = sorted(d for d in os.listdir(ROOT)
                      if os.path.isdir(os.path.join(ROOT, d)) and ' - ' in d)
    if args:
        products = [p for p in products if args[0].upper() in p.upper()]
        if not products:
            print(f'no product matches {args[0]!r} - nothing was checked')
            return 2
    return max([run(p) for p in products] or [0])


if __name__ == '__main__':
    sys.exit(main())
